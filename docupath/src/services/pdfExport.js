import { jsPDF } from 'jspdf';

/**
 * Generate and download a PDF from document text with optional signature image.
 */
export function generatePDF(text, title = 'DocuPath Document', signatureDataUrl = null) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 20;
  const maxWidth = pageWidth - margin * 2;

  // Header
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text('Generated by DocuPath — docupath.app', margin, 12);
  doc.setDrawColor(200);
  doc.line(margin, 15, pageWidth - margin, 15);

  // Title
  doc.setFontSize(16);
  doc.setTextColor(30);
  doc.text(title, margin, 28);

  // Body
  doc.setFontSize(11);
  doc.setTextColor(60);
  const lines = doc.splitTextToSize(text, maxWidth);
  let y = 40;
  const lineHeight = 6;

  lines.forEach((line) => {
    if (y + lineHeight > pageHeight - 40) {
      doc.addPage();
      y = 20;
    }
    doc.text(line, margin, y);
    y += lineHeight;
  });

  // Render Signature Image if available
  if (signatureDataUrl) {
    if (y + 35 > pageHeight - 30) {
      doc.addPage();
      y = 25;
    } else {
      y += 10;
    }
    doc.setFontSize(9);
    doc.setTextColor(100);
    doc.text('DIGITAL SIGNATURE ATTACHED:', margin, y);
    y += 4;
    try {
      doc.addImage(signatureDataUrl, 'PNG', margin, y, 50, 20);
      y += 22;
      doc.setFontSize(8);
      doc.text(`Digitally signed via DocuPath on ${new Date().toLocaleDateString()}`, margin, y);
    } catch (e) {
      console.error('Signature image render error:', e);
    }
  }

  // Footer Page Numbers
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150);
    doc.text(
      `Page ${i} of ${pageCount}`,
      pageWidth / 2,
      290,
      { align: 'center' }
    );
  }

  doc.save(`${title.replace(/[^a-zA-Z0-9]/g, '_')}.pdf`);
}

/**
 * Generate and download a formatted Word (.doc / .docx) file.
 */
export function generateDOCX(text, title = 'DocuPath Document') {
  const htmlContent = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head>
      <meta charset='utf-8'>
      <title>${title}</title>
      <style>
        body { font-family: 'Calibri', 'Arial', sans-serif; font-size: 11pt; line-height: 1.6; color: #111; margin: 1in; }
        h1 { font-size: 16pt; color: #1d5cff; border-bottom: 1px solid #ccc; padding-bottom: 6px; }
        pre { font-family: 'Calibri', 'Arial', sans-serif; white-space: pre-wrap; font-size: 11pt; }
        .footer { margin-top: 40px; font-size: 9pt; color: #777; border-top: 1px solid #ddd; padding-top: 10px; }
      </style>
    </head>
    <body>
      <h1>${title}</h1>
      <pre>${text}</pre>
      <div class="footer">Generated via DocuPath — ${new Date().toLocaleDateString()}</div>
    </body>
    </html>
  `;

  const blob = new Blob(['\ufeff' + htmlContent], {
    type: 'application/msword;charset=utf-8',
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${title.replace(/[^a-zA-Z0-9]/g, '_')}.doc`;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Share document or deadline link via WhatsApp.
 */
export function shareViaWhatsApp(title, summaryText) {
  const message = `📑 *DocuPath Document: ${title}*\n\n${summaryText}\n\nCreated with DocuPath — https://docupath.app`;
  const url = `https://wa.me/?text=${encodeURIComponent(message)}`;
  window.open(url, '_blank');
}

/**
 * Send email reminder via mailto protocol.
 */
export function sendEmailReminder(subject, body) {
  const url = `mailto:?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  window.open(url, '_blank');
}

/**
 * Copy document text to clipboard.
 */
export async function copyToClipboard(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}
